"""Extract the Creality RFID tag keys from your own copy of the stock CFS firmware.

OpenCFS never ships these keys. This tool reads a stock application image (or a
full-flash dump) that you already have and writes a local C++ header for the
board port's CrealityTagCrypto. Keep the header out of version control.

How the stock firmware stores them (docs/spec/10-board-port.md section 5):
the 48-byte key table sits right before the standard AES S-box. It has four
12-byte entries; word 0 of each entry builds the Key A derivation key (K1) and
word 1 the record decryption key (K2). The table is found by locating the S-box
and the inverse S-box, then checked against a literal in the image that points
to it.

Only SHA-256 fingerprints are printed, never the keys.

Usage: tools/re/extract_tag_keys.py IMAGE --out cpp/board/k2cfs/local/creality_keys.hpp
"""
import argparse
import hashlib
import struct
import sys
from pathlib import Path


def aes_sboxes():
    sbox = [0] * 256
    p = q = 1
    while True:
        p = p ^ ((p << 1) & 0xFF) ^ (0x1B if p & 0x80 else 0)
        q ^= q << 1
        q ^= q << 2
        q ^= q << 4
        q &= 0xFF
        if q & 0x80:
            q ^= 0x09
        rot = lambda v, n: ((v << n) | (v >> (8 - n))) & 0xFF
        sbox[p] = q ^ rot(q, 1) ^ rot(q, 2) ^ rot(q, 3) ^ rot(q, 4) ^ 0x63
        if p == 1:
            break
    sbox[0] = 0x63
    inv = [0] * 256
    for i, v in enumerate(sbox):
        inv[v] = i
    return bytes(sbox), bytes(inv)


TABLE_LEN = 48
CANDIDATE_BASES = (0x08003000, 0x08000000, 0x08010000)


def find_table(img):
    sbox, inv = aes_sboxes()
    pos = img.find(sbox + inv)
    if pos < 0:
        raise SystemExit("standard AES S-box + inverse S-box not found: not a supported image")
    table = pos - TABLE_LEN
    if table < 0:
        raise SystemExit("S-box too close to the start of the image")
    for base in CANDIDATE_BASES:
        want = struct.pack("<I", base + table)
        for off in range(0, len(img) - 3, 4):
            if img[off:off + 4] == want:
                return table, base, off
    raise SystemExit("no literal points to the key table: unknown layout, refusing to guess")


def keys_from_table(raw):
    k1 = b"".join(raw[i * 12:i * 12 + 4] for i in range(4))
    k2 = b"".join(raw[i * 12 + 4:i * 12 + 8] for i in range(4))
    for name, k in (("K1", k1), ("K2", k2)):
        if len(set(k)) < 4:
            raise SystemExit(f"{name} looks degenerate: unexpected image layout")
    return k1, k2


def fingerprint(b):
    return hashlib.sha256(b).hexdigest()[:16]


def header(k1, k2, image_name, image_fp):
    arr = lambda k: ", ".join(f"0x{x:02X}" for x in k)
    return f"""// Generated by extract_tag_keys.py from {image_name} (sha256 {image_fp}).
// Creality tag keys from your own firmware image. DO NOT COMMIT OR PUBLISH.
#pragma once

#include <cstdint>

namespace cfs::board::local {{

// AES-128 key that derives MIFARE Key A from the tag UID (K1).
constexpr uint8_t kCrealityKeyAKdf[16] = {{{arr(k1)}}};
// AES-128 key that decrypts record blocks 4..6 (K2).
constexpr uint8_t kCrealityRecordKey[16] = {{{arr(k2)}}};

}}  // namespace cfs::board::local
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("image", type=Path)
    ap.add_argument("--out", type=Path, help="header to write (omit to only print fingerprints)")
    a = ap.parse_args()
    img = a.image.read_bytes()
    table, base, lit = find_table(img)
    k1, k2 = keys_from_table(img[table:table + TABLE_LEN])
    img_fp = fingerprint(img)
    print(f"image   {a.image.name}  sha256 {img_fp}")
    print(f"table   0x{base + table:08X} (base 0x{base:08X}, literal at 0x{base + lit:08X})")
    print(f"K1 sha256 {fingerprint(k1)}")
    print(f"K2 sha256 {fingerprint(k2)}")
    if a.out:
        a.out.parent.mkdir(parents=True, exist_ok=True)
        a.out.write_text(header(k1, k2, a.image.name, img_fp), encoding="utf-8", newline="\n")
        print(f"wrote   {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
